-- ============================================================================
-- V1__baseline.sql : FlatMap + SafetyRoad 통합 스키마 (구조만, 데이터 INSERT 없음)
--
-- 근거: docs/schema-merge.md + 확정 결정 사항
--  * 깨진 시설 데이터와 danger_zone 데이터는 이식하지 않는다. 구조만 만든다.
--  * safety_facility 는 자연키 UNIQUE (facility_type, location). 적재는 ON CONFLICT 로 처리한다.
--  * 시설 타입은 CCTV / SECURITY_LIGHT / POLICE. POLICE 에 소방서는 포함하지 않는다.
--  * steep_slope_areas 에는 risk_level 을 두지 않는다. 경사도(°)와 geometry 만 둔다.
--  * danger_zone 은 facility_density_grid 로 이름을 바꾸고 "위험" 표현을 쓰지 않는다.
--  * 공간 쿼리는 geography 표현식 GiST 인덱스를 쓰고, 거리는 미터 단위로 계산한다.
--  * accident_records / route_segments / road_segments / routes 는 만들지 않는다.
--  * FlatMap security_lights 100건(성남 밖)은 가져오지 않는다. 테이블 자체를 만들지 않는다.
--
-- 호환 메모: 아직 JPA 엔티티가 latitude/longitude 로 읽고 쓰는 FlatMap 전용 테이블은
-- 두 컬럼을 유지하고, geom 은 두 값에서 파생되는 생성 컬럼으로 둔다(어긋날 수 없다).
-- 소비 코드를 JdbcTemplate + geom 으로 옮긴 뒤 후속 마이그레이션에서 lat/lng 를 제거한다.
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS postgis;

-- ----------------------------------------------------------------------------
-- 비공간 테이블 (JPA 유지)
-- ----------------------------------------------------------------------------
CREATE TABLE users (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        timestamp(6),
    nickname          varchar(255),
    profile_image_url varchar(255),
    provider          varchar(255) NOT NULL,
    provider_id       varchar(255) NOT NULL,
    CONSTRAINT users_provider_check CHECK (provider IN ('KAKAO', 'LOCAL')),
    CONSTRAINT uq_users_provider_provider_id UNIQUE (provider, provider_id)
);

CREATE TABLE favorites (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address    varchar(255),
    created_at timestamp(6),
    latitude   double precision,
    longitude  double precision,
    name       varchar(255),
    user_id    bigint NOT NULL,
    CONSTRAINT fk_favorites_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX idx_favorites_user_id ON favorites (user_id);

-- ----------------------------------------------------------------------------
-- 안전시설 통합 (FlatMap cctv_locations + SafetyRoad safety_facility)
-- ----------------------------------------------------------------------------
CREATE TABLE safety_facility (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_type varchar(30)  NOT NULL,
    name          varchar(255),
    address       varchar(255),
    region_code   varchar(10),
    location      geometry(Point, 4326) NOT NULL,
    data_source   varchar(80)  NOT NULL,
    created_at    timestamp(6) NOT NULL DEFAULT now(),
    updated_at    timestamp(6) NOT NULL DEFAULT now(),
    -- POLICE 는 경찰 시설만. 소방서는 포함하지 않는다.
    CONSTRAINT chk_safety_facility_type CHECK (facility_type IN ('CCTV', 'SECURITY_LIGHT', 'POLICE')),
    -- 자연키: 같은 종류가 같은 좌표에 중복 적재되는 것을 막는다.
    CONSTRAINT uq_safety_facility_type_location UNIQUE (facility_type, location)
);
COMMENT ON TABLE  safety_facility IS '안전시설 통합 테이블. 적재는 INSERT ... ON CONFLICT (facility_type, location) 로 한다.';
COMMENT ON COLUMN safety_facility.facility_type IS 'CCTV | SECURITY_LIGHT | POLICE(경찰 시설만, 소방서 제외)';
COMMENT ON COLUMN safety_facility.location IS 'WGS84 Point (경도, 위도 순). 거리는 location::geography 로 미터 단위 계산';

-- ----------------------------------------------------------------------------
-- 시설 밀도 격자 (SafetyRoad danger_zone 의 후신). 격자 안의 안전시설 밀도를 나타낸다.
-- ----------------------------------------------------------------------------
CREATE TABLE facility_density_grid (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grid_i         integer       NOT NULL,
    grid_j         integer       NOT NULL,
    grid_polygon   geometry(Polygon, 4326) NOT NULL,
    facility_count integer       NOT NULL DEFAULT 0,
    density_score  numeric(5, 2) NOT NULL,
    density_level  varchar(20)   NOT NULL,
    score_version  smallint      NOT NULL DEFAULT 1,
    calculated_at  timestamp(6)  NOT NULL DEFAULT now(),
    CONSTRAINT chk_density_level CHECK (density_level IN ('LOW_DENSITY', 'MEDIUM', 'HIGH_DENSITY')),
    CONSTRAINT chk_density_facility_count CHECK (facility_count >= 0),
    CONSTRAINT uq_facility_density_grid_cell UNIQUE (grid_i, grid_j)
);
COMMENT ON TABLE  facility_density_grid IS '300m 격자별 안전시설 밀도. 시설이 적다는 것은 위험이 아니라 시설 데이터가 적다는 뜻이다.';
COMMENT ON COLUMN facility_density_grid.density_level IS 'LOW_DENSITY | MEDIUM | HIGH_DENSITY (시설 밀도 기준)';

-- ----------------------------------------------------------------------------
-- FlatMap 전용 공간 테이블 (그대로 유지 + geom 생성 컬럼)
-- ----------------------------------------------------------------------------
CREATE TABLE accident_zones (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6),
    latitude    double precision,
    longitude   double precision,
    name        varchar(255),
    region_code varchar(255),
    type        varchar(255),
    geom        geometry(Point, 4326)
        GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)) STORED
);

CREATE TABLE protected_zones (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address     varchar(255),
    created_at  timestamp(6),
    latitude    double precision,
    longitude   double precision,
    name        varchar(255),
    region_code varchar(255),
    type        varchar(255),
    geom        geometry(Point, 4326)
        GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)) STORED
);

CREATE TABLE welfare_facilities (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address     varchar(255),
    created_at  timestamp(6),
    latitude    double precision,
    longitude   double precision,
    name        varchar(255),
    phone       varchar(255),
    region_code varchar(255),
    type        varchar(255),
    geom        geometry(Point, 4326)
        GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)) STORED
);

CREATE TABLE shade_shelters (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address     varchar(255),
    created_at  timestamp(6),
    latitude    double precision,
    longitude   double precision,
    name        varchar(255),
    region_code varchar(255),
    geom        geometry(Point, 4326)
        GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)) STORED
);

CREATE TABLE senior_centers (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address     varchar(255),
    created_at  timestamp(6),
    latitude    double precision,
    longitude   double precision,
    name        varchar(255),
    phone       varchar(255),
    region_code varchar(255),
    geom        geometry(Point, 4326)
        GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)) STORED
);

-- ----------------------------------------------------------------------------
-- 급경사지: 붕괴위험 지정지 표본. 경사도(°)와 geometry 만 둔다.
-- risk_level 컬럼은 만들지 않는다 (보행난이도 임계값 3.18°/4.76° 를 이 데이터에 적용하지 않는다).
-- ----------------------------------------------------------------------------
CREATE TABLE steep_slope_areas (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6),
    grade       double precision,
    latitude    double precision,
    longitude   double precision,
    name        varchar(255),
    region_code varchar(255),
    source      varchar(255),
    sigungu     varchar(255),
    eupmyeon    varchar(255),
    jibun       varchar(255),
    is_mountain boolean DEFAULT false,
    geom        geometry(Point, 4326)
        GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)) STORED,
    -- 단위는 각도(°)이며 %가 아니다.
    CONSTRAINT chk_steep_slope_grade_deg CHECK (grade IS NULL OR (grade >= 0 AND grade < 90))
);
COMMENT ON TABLE  steep_slope_areas IS '붕괴위험 지정지 표본. 붕괴위험 경고 레이어용이며 보행난이도 등급 대상이 아니다.';
COMMENT ON COLUMN steep_slope_areas.grade IS '경사도, 단위 각도(°). % 아님.';

-- ----------------------------------------------------------------------------
-- 인덱스
--  * geography 표현식 GiST: ST_DWithin(col::geography, point::geography, 미터) 용
--  * geometry GiST: 사각형/포함/교차(ST_Within, ST_Intersects) 용 — 시설, 격자만
--  * region_code: LIKE 'prefix%' 조회용 (varchar_pattern_ops)
-- ----------------------------------------------------------------------------
CREATE INDEX idx_safety_facility_location_geom ON safety_facility USING GIST (location);
CREATE INDEX idx_safety_facility_location_geog ON safety_facility USING GIST ((location::geography));
CREATE INDEX idx_safety_facility_type          ON safety_facility (facility_type);
CREATE INDEX idx_safety_facility_region        ON safety_facility (region_code varchar_pattern_ops);

CREATE INDEX idx_facility_density_grid_polygon_geom ON facility_density_grid USING GIST (grid_polygon);
CREATE INDEX idx_facility_density_grid_polygon_geog ON facility_density_grid USING GIST ((grid_polygon::geography));

CREATE INDEX idx_accident_zones_geom_geog      ON accident_zones      USING GIST ((geom::geography));
CREATE INDEX idx_protected_zones_geom_geog     ON protected_zones     USING GIST ((geom::geography));
CREATE INDEX idx_welfare_facilities_geom_geog  ON welfare_facilities  USING GIST ((geom::geography));
CREATE INDEX idx_shade_shelters_geom_geog      ON shade_shelters      USING GIST ((geom::geography));
CREATE INDEX idx_senior_centers_geom_geog      ON senior_centers      USING GIST ((geom::geography));
CREATE INDEX idx_steep_slope_areas_geom_geog   ON steep_slope_areas   USING GIST ((geom::geography));

CREATE INDEX idx_accident_zones_region     ON accident_zones     (region_code varchar_pattern_ops);
CREATE INDEX idx_protected_zones_region    ON protected_zones    (region_code varchar_pattern_ops);
CREATE INDEX idx_welfare_facilities_region ON welfare_facilities (region_code varchar_pattern_ops);
CREATE INDEX idx_shade_shelters_region     ON shade_shelters     (region_code varchar_pattern_ops);
CREATE INDEX idx_senior_centers_region     ON senior_centers     (region_code varchar_pattern_ops);
CREATE INDEX idx_steep_slope_areas_region  ON steep_slope_areas  (region_code varchar_pattern_ops);
CREATE INDEX idx_steep_slope_areas_source  ON steep_slope_areas  (source);
